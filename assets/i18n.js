export function getLang() {
  try { const l = localStorage.getItem("qwik-lang"); if (l === "de" || l === "en") return l; } catch (e) { /* ignore */ }
  return (navigator.language || "en").toLowerCase().startsWith("de") ? "de" : "en";
}

const originals = new Map();
export function applyLang(lang) {
  document.documentElement.lang = lang;
  try { localStorage.setItem("qwik-lang", lang); } catch (e) { /* ignore */ }
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    if (!originals.has(el)) originals.set(el, el.innerHTML);
    const k = el.getAttribute("data-i18n");
    el.innerHTML = lang === "de" && DE[k] ? escapeHtml(DE[k]) : originals.get(el);
  });
  document.querySelectorAll("[data-i18n-list]").forEach((el) => {
    if (!originals.has(el)) originals.set(el, el.innerHTML);
    const k = el.getAttribute("data-i18n-list");
    el.innerHTML = lang === "de" && Array.isArray(DE[k]) ? DE[k].map((t) => `<li>${escapeHtml(t)}</li>`).join("") : originals.get(el);
  });
  document.querySelectorAll(".lang button").forEach((b) => b.setAttribute("aria-pressed", String(b.dataset.lang === lang)));
}

export function t(key, lang, fallback) { return lang === "de" && DE[key] ? DE[key] : fallback; }

export function escapeHtml(s) {
  return String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}

export function initLangSwitch(onChange) {
  let lang = getLang();
  applyLang(lang);
  document.querySelectorAll(".lang button").forEach((b) => b.addEventListener("click", () => {
    lang = b.dataset.lang; applyLang(lang); if (onChange) onChange(lang);
  }));
  return () => lang;
}
